#!/bin/bash
# Builds "NSE Research.app" in ~/Applications. Double-click it (or keep it in the Dock) to open
# the dashboard: it starts Streamlit from this folder's .venv if it isn't already running, then
# opens http://localhost:8501 in your default browser. The server listens on 127.0.0.1 only, so
# nothing is reachable from other machines.
# Re-run this script after moving the project folder. Remove with:  rm -rf ~/Applications/"NSE Research.app"
set -euo pipefail
PROJECT="$(cd "$(dirname "$0")/.." && pwd)"
APP="$HOME/Applications/NSE Research.app"
PORT=8501

if [ ! -x "$PROJECT/.venv/bin/streamlit" ]; then
  echo "No Streamlit in $PROJECT/.venv. Set up the venv first (see README, section 2)." >&2
  exit 1
fi

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$PROJECT/data/logs"

cat > "$APP/Contents/Info.plist" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>NSE Research</string>
  <key>CFBundleDisplayName</key><string>NSE Research</string>
  <key>CFBundleIdentifier</key><string>local.nseresearch.dashboard</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
PL

cat > "$APP/Contents/MacOS/launch" <<SH
#!/bin/bash
# Generated by scripts/install_mac_app.sh
PROJECT="$PROJECT"
PORT=$PORT
URL="http://localhost:\$PORT"
LOG="\$PROJECT/data/logs/dashboard.log"
up() { /usr/bin/curl -s -o /dev/null --max-time 1 "\$URL/_stcore/health"; }
if ! up; then
  cd "\$PROJECT" || exit 1
  echo "===== \$(date) =====" >> "\$LOG"
  nohup "\$PROJECT/.venv/bin/streamlit" run app/streamlit_app.py \\
      --server.headless true --server.address 127.0.0.1 --server.port \$PORT \\
      --browser.gatherUsageStats false >> "\$LOG" 2>&1 &
  for _ in \$(seq 1 60); do up && break; sleep 0.5; done
fi
if up; then
  /usr/bin/open "\$URL"
else
  /usr/bin/osascript -e 'display alert "NSE Research did not start" message "See data/logs/dashboard.log in the project folder."'
fi
SH
chmod +x "$APP/Contents/MacOS/launch"

echo "Installed: $APP"
echo "Open it from Finder > Applications (your user's), Spotlight (type 'NSE Research'), or drag it to the Dock."
echo "Stop the server with:  $PROJECT/scripts/stop_dashboard.sh"
